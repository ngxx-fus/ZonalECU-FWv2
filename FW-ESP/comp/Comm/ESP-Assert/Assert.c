/** @brief ZE assert Interrupt service routine
 *  @param p_context The context passes into user's callback */
static void ze_assert_isr(void * p_context) {

    ze_assert_callback_arg_t * p_assert_context = (ze_assert_callback_arg_t *) p_context;

    if(IS_NOT_NULL(gp_ze_assert_callback)) {
        gp_ze_assert_callback(p_assert_context);
    }
}

/* PUBLIC FUNCTIONS *************************************************************************************************************
 ********************************************************************************************************************************/

/** @brief Set the user's callback function when assert fail
 *  @param p_callback
 *  @return return description */
ze_err_t ZE_Assert_CallbackSet(ze_assert_callback_t p_callback) {
    if(IS_NULL(p_callback)){
        return ZE_ERR_INVALID_ARG;
    }
    gp_ze_assert_callback = p_callback;
    (void)(ze_assert_isr);
    return ZE_SUCCESS;
}

